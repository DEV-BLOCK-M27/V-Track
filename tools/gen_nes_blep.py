"""The NES chip core's band-limited step (firmware/src/nes_blep.h): a Kaiser-windowed sinc impulse, TAPS samples
long, at PHASES + 1 sub-sample offsets (0 .. 1 sample). A step at time i + p/PHASES adds its height times
kernel[p][k] to sample i + k (nes.c splits a step between two neighbouring phases by the rest of its time); the
running sum of those is the band-limited step. Every phase sums to exactly 1 << KBITS, so the running
sum lands on the step's height without drift.
  tools/gen_nes_blep.py > firmware/src/nes_blep.h"""
import math

TAPS = 32          # kernel length in samples
PHASES = 32        # sub-sample offsets (nes.c interpolates between two)
KBITS = 15         # the taps of one phase sum to 1 << KBITS
CUTOFF = 0.38      # the sinc's cutoff, a fraction of the sample rate: 16.8 kHz at 44.1 kHz (the NES's own audio out
                   # rolls off from 14 kHz); with the window, -80 dB from 20 kHz on
BETA = 9.0         # the Kaiser window's beta


def i0(x):
    s, t, k = 1.0, 1.0, 1
    while t > 1e-12 * s:
        t *= (x / (2 * k)) ** 2
        s += t
        k += 1
    return s


def kernel(phase):
    """taps k = 0 .. TAPS-1 of an impulse centred between taps TAPS/2-1 and TAPS/2, delayed by phase/PHASES"""
    out = []
    half = TAPS / 2
    for k in range(TAPS):
        u = k - (half - 1) - phase / PHASES            # the impulse at TAPS/2 - 1 + phase/PHASES
        w = u / half                                   # the window, centred on the impulse
        win = i0(BETA * math.sqrt(max(0.0, 1 - w * w))) / i0(BETA)
        s = 2 * CUTOFF * (math.sin(2 * math.pi * CUTOFF * u) / (2 * math.pi * CUTOFF * u) if u else 1.0)
        out.append(s * win)
    total = sum(out)
    q = [round(v / total * (1 << KBITS)) for v in out]
    q[TAPS // 2 - 1 if phase <= PHASES / 2 else TAPS // 2] += (1 << KBITS) - sum(q)   # exact sum: on the peak
    return q


print("/* SPDX-License-Identifier: GPL-3.0-only")
print(" * V-Track: Copyright (C) 2026 Manuel Rubin */")
print("/* generated by tools/gen_nes_blep.py: do not edit. The band-limited step of the NES chip core (nes.c). */")
print(f"#define NES_TAPS {TAPS}u")
print(f"#define NES_PHASE_BITS {PHASES.bit_length() - 1}")
print(f"#define NES_KBITS {KBITS}")
print(f"static const int16_t NES_BLEP[{PHASES} + 1][{TAPS}] = {{")
for p in range(PHASES + 1):
    print("    {" + ", ".join(str(v) for v in kernel(p)) + "},")
print("};")
