"""The NES chip core's band-limited step (firmware/src/nes_blep.h), as a BLEP residual: the band-limited step
(the running integral of a Kaiser-windowed sinc impulse) minus the ideal step, TAPS samples long, at PHASES + 1
sub-sample offsets (0 .. 1 sample). A step of height d at time i + p/PHASES adds d * residual[p][k] to sample i + k
and d to every sample from i + TAPS/2 on (nes.c splits a step between two neighbouring phases by the rest of its
time). The ideal steps are summed exactly, so the output does not drift; the residual is local.
The residual is not the running sum of a sampled impulse: summing samples would raise the aliases that fold to
near 0 Hz (from near the sample rate) by fs / f.
  tools/gen_nes_blep.py > firmware/src/nes_blep.h"""
import math

TAPS = 32          # kernel length in samples
PHASES = 128       # sub-sample offsets (nes.c interpolates between two)
KBITS = 16         # the ideal step is 1 << KBITS: the residual (at most 1/2) just fits 16 bits, clipped to 32767
CUTOFF = 0.38      # the sinc's cutoff, a fraction of the sample rate: 16.8 kHz at 44.1 kHz (the NES's own audio out
                   # rolls off from 14 kHz); with the window, -80 dB from 20 kHz on
BETA = 9.0         # the Kaiser window's beta


def i0(x):
    s, t, k = 1.0, 1.0, 1
    while t > 1e-12 * s:
        t *= (x / (2 * k)) ** 2
        s += t
        k += 1
    return s


def impulse(u):
    """the windowed sinc at u samples from its centre"""
    half = TAPS / 2
    w = u / half
    win = i0(BETA * math.sqrt(max(0.0, 1 - w * w))) / i0(BETA)
    return 2 * CUTOFF * (math.sin(2 * math.pi * CUTOFF * u) / (2 * math.pi * CUTOFF * u) if u else 1.0) * win


GRID = 256                                             # integration steps a sample (Simpson)


def integral(a, b):
    n = max(2, int(round((b - a) * GRID)) // 2 * 2)
    h = (b - a) / n
    return h / 3 * sum((1 if i in (0, n) else 4 if i % 2 else 2) * impulse(a + i * h) for i in range(n + 1))


TOTAL = integral(-TAPS / 2, TAPS / 2)


def kernel(phase):
    """taps k = 0 .. TAPS-1: the band-limited step centred at TAPS/2 - 1 + phase/PHASES minus the ideal step, which
    is 1 from tap TAPS/2 on"""
    out, half, s, prev = [], TAPS // 2, 0.0, -TAPS / 2
    for k in range(TAPS):
        u = k - (half - 1) - phase / PHASES            # tap k, from the step
        s += integral(prev, u) if u > prev else 0.0
        prev = max(prev, u)
        out.append(max(-32767, min(32767, round((s / TOTAL - (1 if k >= half else 0)) * (1 << KBITS)))))
    return out


print("/* SPDX-License-Identifier: GPL-3.0-only")
print(" * V-Track: Copyright (C) 2026 Manuel Rubin */")
print("/* generated by tools/gen_nes_blep.py: do not edit. The band-limited step of the NES chip core (nes.c): the")
print(" * BLEP residual, the band-limited step minus the ideal step that rises at tap NES_TAPS / 2. */")
print(f"#define NES_TAPS {TAPS}u")
print(f"#define NES_PHASE_BITS {PHASES.bit_length() - 1}")
print(f"#define NES_KBITS {KBITS}")
print(f"static const int16_t NES_BLEP[{PHASES} + 1][{TAPS}] = {{")
for p in range(PHASES + 1):
    print("    {" + ", ".join(str(v) for v in kernel(p)) + "},")
print("};")
